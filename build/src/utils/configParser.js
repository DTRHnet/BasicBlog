import Joi from 'joi';
import yaml from 'js-yaml';
import fs from 'fs';
import path from 'path';
import { logInfo, logWarn, logError } from './logger.js';

/**
 * Schema for config.yaml validation
 */
const configSchema = Joi.object({
    title: Joi.string().required().min(1).max(200),
    theme: Joi.string().valid('light', 'dark').default('light'),
    output_dir: Joi.string().default('./build'),
    multi_page: Joi.boolean().default(false),
    author: Joi.string().optional(),
    description: Joi.string().optional(),
}).unknown(true); // Allow additional fields for extensibility

/**
 * Default configuration values
 */
const defaultConfig = {
    title: 'Welcome to BasicBlog',
    theme: 'light',
    output_dir: './build',
    multi_page: false,
    author: '',
    description: 'A blog generated by BasicBlog',
};

/**
 * Parse and validate config.yaml file
 * @param {string} configPath - Path to config.yaml file
 * @returns {Object} Parsed and validated configuration
 */
export function parseConfig(configPath) {
    try {
        logInfo(`Parsing configuration file: ${configPath}`);

        // Check if file exists
        if (!fs.existsSync(configPath)) {
            logWarn(`Configuration file not found at ${configPath}. Using default configuration.`);
            return defaultConfig;
        }

        // Read and parse YAML
        const fileContents = fs.readFileSync(configPath, 'utf8');
        const parsedConfig = yaml.load(fileContents);

        if (!parsedConfig || typeof parsedConfig !== 'object') {
            logWarn('Invalid YAML structure in config.yaml. Using default configuration.');
            return defaultConfig;
        }

        // Validate against schema
        const { error, value } = configSchema.validate(parsedConfig, {
            abortEarly: false,
            stripUnknown: false,
        });

        if (error) {
            logWarn(`Validation errors in config.yaml: ${error.details.map(d => d.message).join(', ')}. Using defaults for invalid fields.`);
            // Merge with defaults for any missing/invalid fields
            return { ...defaultConfig, ...value };
        }

        logInfo('Configuration parsed successfully', { config: value });
        return value;

    } catch (err) {
        if (err.name === 'YAMLException') {
            logError(`Invalid YAML syntax in config.yaml: ${err.message}. Using default configuration.`, err);
        } else {
            logError(`Error reading config.yaml: ${err.message}. Using default configuration.`, err);
        }
        return defaultConfig;
    }
}

/**
 * Parse menu.json file
 * @param {string} menuPath - Path to menu.json file
 * @returns {Array} Array of menu items
 */
export function parseMenu(menuPath) {
    try {
        logInfo(`Parsing menu file: ${menuPath}`);

        if (!fs.existsSync(menuPath)) {
            logWarn(`Menu file not found at ${menuPath}. Using empty menu.`);
            return [];
        }

        const fileContents = fs.readFileSync(menuPath, 'utf8');
        const menuData = JSON.parse(fileContents);

        if (!Array.isArray(menuData)) {
            logWarn('menu.json must be an array. Using empty menu.');
            return [];
        }

        // Validate menu items
        const validatedMenu = menuData.filter((item, index) => {
            if (!item.label || typeof item.label !== 'string') {
                logWarn(`Menu item at index ${index} missing valid 'label'. Skipping.`);
                return false;
            }
            if (!item.url || typeof item.url !== 'string') {
                logWarn(`Menu item at index ${index} missing valid 'url'. Skipping.`);
                return false;
            }
            return true;
        });

        logInfo(`Menu parsed successfully with ${validatedMenu.length} items`);
        return validatedMenu;

    } catch (err) {
        if (err instanceof SyntaxError) {
            logError(`Invalid JSON syntax in menu.json: ${err.message}. Using empty menu.`, err);
        } else {
            logError(`Error reading menu.json: ${err.message}. Using empty menu.`, err);
        }
        return [];
    }
}

/**
 * Parse entries.json file
 * @param {string} entriesPath - Path to entries.json file
 * @returns {Object} Object mapping pane IDs to content arrays
 */
export function parseEntries(entriesPath) {
    try {
        logInfo(`Parsing entries file: ${entriesPath}`);

        if (!fs.existsSync(entriesPath)) {
            logWarn(`Entries file not found at ${entriesPath}. Using empty entries.`);
            return {};
        }

        const fileContents = fs.readFileSync(entriesPath, 'utf8');
        const entriesData = JSON.parse(fileContents);

        if (!entriesData || typeof entriesData !== 'object' || Array.isArray(entriesData)) {
            logWarn('entries.json must be an object. Using empty entries.');
            return {};
        }

        // Validate entries structure
        const validatedEntries = {};

        for (const [paneId, entries] of Object.entries(entriesData)) {
            if (!Array.isArray(entries)) {
                logWarn(`Entries for pane '${paneId}' must be an array. Skipping.`);
                continue;
            }

            validatedEntries[paneId] = entries.filter((entry, index) => {
                if (!entry.type || !['text', 'markdown', 'html'].includes(entry.type)) {
                    logWarn(`Entry at index ${index} in pane '${paneId}' has invalid type. Skipping.`);
                    return false;
                }
                if (!entry.content || typeof entry.content !== 'string') {
                    logWarn(`Entry at index ${index} in pane '${paneId}' missing valid content. Skipping.`);
                    return false;
                }
                return true;
            });
        }

        const totalEntries = Object.values(validatedEntries).reduce((sum, arr) => sum + arr.length, 0);
        logInfo(`Entries parsed successfully with ${totalEntries} total entries across ${Object.keys(validatedEntries).length} panes`);

        return validatedEntries;

    } catch (err) {
        if (err instanceof SyntaxError) {
            logError(`Invalid JSON syntax in entries.json: ${err.message}. Using empty entries.`, err);
        } else {
            logError(`Error reading entries.json: ${err.message}. Using empty entries.`, err);
        }
        return {};
    }
}

export default {
    parseConfig,
    parseMenu,
    parseEntries,
};
