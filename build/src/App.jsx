import React, { useState, useEffect } from 'react';
import { BrowserRouter as Router, Routes, Route } from 'react-router-dom';
import Navigation from './components/Navigation';
import HomePage from './pages/HomePage';
import './App.css';

/**
 * Main App component
 * Handles theme management and routing
 */
function App() {
  // Get blog data from window object (injected during build)
  const blogData = window.__BLOG_DATA__ || {
    config: {
      title: 'BasicBlog',
      theme: 'light',
      author: '',
      description: 'A blog generated by BasicBlog',
    },
    menu: [],
    panes: [{ name: 'main', width: 100 }],
    entries: {},
  };

  const [theme, setTheme] = useState(blogData.config.theme || 'light');

  // Apply theme to document
  useEffect(() => {
    const root = document.documentElement;
    if (theme === 'dark') {
      root.classList.add('dark');
    } else {
      root.classList.remove('dark');
    }
  }, [theme]);

  // Update document title and meta tags
  useEffect(() => {
    document.title = blogData.config.title;

    // Update meta description
    const metaDescription = document.querySelector('meta[name="description"]');
    if (metaDescription && blogData.config.description) {
      metaDescription.setAttribute('content', blogData.config.description);
    }

    // Update author meta tag
    const metaAuthor = document.querySelector('meta[name="author"]');
    if (metaAuthor && blogData.config.author) {
      metaAuthor.setAttribute('content', blogData.config.author);
    }
  }, [blogData.config]);

  const toggleTheme = () => {
    setTheme(prevTheme => prevTheme === 'light' ? 'dark' : 'light');
  };

  return (
    <Router>
      <div className="min-h-screen bg-background text-foreground transition-colors duration-300">
        <Navigation
          menuItems={blogData.menu}
          title={blogData.config.title}
          theme={theme}
          onThemeToggle={toggleTheme}
        />

        <main>
          <Routes>
            <Route
              path="/"
              element={
                <HomePage
                  panes={blogData.panes}
                  entries={blogData.entries}
                />
              }
            />
            {/* Additional routes can be added here for multi-page support */}
          </Routes>
        </main>

        <footer className="border-t mt-12">
          <div className="container mx-auto px-4 py-6 text-center text-sm text-muted-foreground">
            <p>
              {blogData.config.author && `© ${new Date().getFullYear()} ${blogData.config.author}. `}
              Powered by <span className="font-semibold text-primary">BasicBlog</span>
            </p>
          </div>
        </footer>
      </div>
    </Router>
  );
}

export default App;
